"""Writes the two experiment workload configurations (run once; output is version-controlled).

Config A (no-rule):   replicas only - placement left entirely to the default scheduler.
Config B (spread):    same, plus topologySpreadConstraints maxSkew=1 on kubernetes.io/hostname,
                      whenUnsatisfiable=DoNotSchedule (the "declared intent" under test).

Containers use registry.k8s.io/pause:3.10, which is preloaded in every kind node image, so no
image download is needed: the experiments study where pods are placed, not application behaviour.
"""
from pathlib import Path

import yaml

NAMESPACE = "placement-drift-exp"
SERVICES = ["paymentservice", "cartservice", "checkoutservice", "catalogservice"]
REPLICAS = 3
IMAGE = "registry.k8s.io/pause:3.10"
OUT_DIR = Path(__file__).resolve().parents[3] / "deploy" / "experiments" / "placement-drift"


def _deployment(name: str, spread: bool) -> dict:
    spec = {
        "containers": [{
            "name": name,
            "image": IMAGE,
            "imagePullPolicy": "IfNotPresent",
            # Small, fixed requests, so the scheduler has a real size to place but every node has room.
            "resources": {
                "requests": {"cpu": "50m", "memory": "16Mi"},
                "limits": {"cpu": "50m", "memory": "16Mi"},
            },
        }],
        # pause has nothing to shut down, so old pods disappear at once and runs stay short.
        "terminationGracePeriodSeconds": 0,
    }
    if spread:
        spec["topologySpreadConstraints"] = [{
            "maxSkew": 1,
            "topologyKey": "kubernetes.io/hostname",
            "whenUnsatisfiable": "DoNotSchedule",
            "labelSelector": {"matchLabels": {"app": name}},
        }]
    return {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": {"name": name, "namespace": NAMESPACE, "labels": {"experiment": "placement-drift"}},
        "spec": {
            "replicas": REPLICAS,
            "selector": {"matchLabels": {"app": name}},
            "template": {"metadata": {"labels": {"app": name, "experiment": "placement-drift"}}, "spec": spec},
        },
    }


def _service(name: str) -> dict:
    return {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": {"name": name, "namespace": NAMESPACE, "labels": {"experiment": "placement-drift"}},
        "spec": {"selector": {"app": name}, "ports": [{"port": 80, "targetPort": 80}]},
    }


def write(config_name: str, spread: bool) -> Path:
    docs = [{"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": NAMESPACE}}]
    for name in SERVICES:
        docs += [_deployment(name, spread), _service(name)]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"{config_name}.yaml"
    header = f"# Generated by experiments/placement_drift/live/generate_workloads.py - config {config_name}\n"
    path.write_text(header + yaml.safe_dump_all(docs, sort_keys=False), encoding="utf-8")
    return path


if __name__ == "__main__":
    print(write("config-a-no-rule", spread=False))
    print(write("config-b-topology-spread", spread=True))
